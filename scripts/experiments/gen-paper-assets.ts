const pairRate = (pairs: Array<[boolean | null, boolean | null]>) => {
  let n = 0;
  let d = 0;
  for (const [a, b] of pairs) {
    if (a === null || b === null) continue;
    n++;
    if (a !== b) d++;
  }
  return n > 0 ? d / n : 0;
};
